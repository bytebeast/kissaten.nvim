-- Assemble the GitHub Pages site into ./_site (site/ + images + generated colors.css):
--   nvim --headless -u NONE -i NONE -l scripts/build_site.lua
vim.opt.rtp:prepend(vim.fn.getcwd())
local Config = require("kissaten.config")
local Colors = require("kissaten.colors")

local out = "_site"
local images = {
  "assets/social-preview.png",
  "assets/screenshots/morning.png",
  "assets/screenshots/afternoon.png",
  "assets/screenshots/evening.png",
  "assets/screenshots/midnight.png",
  "assets/screenshots/graveyard.png",
  "assets/screenshots/picker.png",
  "assets/screenshots/light.png",
  "assets/screenshots/dashboard.png",
  "assets/screenshots/rainbow-variables.png",
}

local function copy(from, to)
  vim.fn.mkdir(vim.fs.dirname(to), "p")
  assert(vim.uv.fs_copyfile(from, to))
end

local function vars(lines, prefix, t)
  local keys = vim.tbl_filter(function(k)
    return type(t[k]) == "string" and not k:find("^_")
  end, vim.tbl_keys(t))
  table.sort(keys)
  for _, k in ipairs(keys) do
    lines[#lines + 1] = ("  --%s-%s: %s;"):format(prefix, k:gsub("_", "-"), t[k])
  end
end

vim.fn.delete(out, "rf")
for name, kind in vim.fs.dir("site", { depth = 10 }) do
  if kind == "file" then
    copy("site/" .. name, out .. "/" .. name)
  end
end
for _, path in ipairs(images) do
  copy(path, out .. "/" .. path)
end
copy("assets/src/vscode-icon.svg", out .. "/favicon.svg")

local lines = { "/* generated by scripts/build_site.lua from lua/kissaten/colors.lua */" }
for _, style in ipairs(Config.styles) do
  local opts = Config.extend({})
  opts.style = style
  local c = Colors.setup(opts)
  -- Any element can carry data-style, so the style cards render in their own colors.
  -- :where() keeps the no-JS default at zero specificity so it never beats a chosen style.
  local selector = ('[data-style="%s"]'):format(style)
  lines[#lines + 1] = (style == Config.defaults.style and ":where(:root),\n" or "") .. selector .. " {"
  lines[#lines + 1] = "  color-scheme: " .. c._background .. ";"
  vars(lines, "p", Colors.palette(style))
  vars(lines, "syn", c.syn)
  vars(lines, "ui", c.ui)
  vars(lines, "diag", c.diag)
  vars(lines, "git", c.git)
  lines[#lines + 1] = "}"
end
local f = assert(io.open(out .. "/colors.css", "w"))
f:write(table.concat(lines, "\n"), "\n")
f:close()
print("built ./" .. out)
